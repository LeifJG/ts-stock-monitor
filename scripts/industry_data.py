_cache = {}


def _load_cache():
    global _cache
    try:
        with open(CACHE_FILE, "r", encoding="utf-8") as f:
            _cache = json.load(f)
    except Exception:
        _cache = {}


def _save_cache():
    os.makedirs(os.path.dirname(CACHE_FILE), exist_ok=True)
    with open(CACHE_FILE, "w", encoding="utf-8") as f:
        json.dump(_cache, f, ensure_ascii=False, indent=1)


def _fresh(entry):
    if not entry or not entry.get("l1"):
        return False
    # 未分类/其他 属于「没取到」的状态，不能因为缓存没过期就一直当作有效结论
    if entry["l1"] in ("未分类", "其他"):
        return False
    try:
        ts = datetime.fromisoformat(entry["updatedAt"])
    except Exception:
        return False
    return datetime.now(timezone.utc) - ts < timedelta(days=CACHE_TTL_DAYS)


def _is_hk(code):
    """港股是 5 位（01810/09988），A 股 6 位；不能用首位数字判断，
    否则 01810（小米）会被当成 A 股去查东财，白等十几秒。"""
    return len(code) == 5


def _fetch_em(code):
    """东财个股基本信息：返回 (name, industry) 或 (None, None)"""
    import akshare as ak
    for i in range(4):
        try:
            df = ak.stock_individual_info_em(symbol=code)
            m = {str(r["item"]): r["value"] for _, r in df.iterrows()}
            name, ind = m.get("股票简称"), m.get("行业")
            if name or ind:
                return (str(name) if name else None, str(ind) if ind else None)
        except Exception:
            time.sleep(0.8 * (i + 1))
    return (None, None)


def resolve(codes, refresh=False):
    _load_cache()
    out, missing, dirty = [], [], False
    to_fetch = []

    for code in codes:
        key = code.strip().upper()
        if not key:
            continue
        cached = _cache.get(key)
        if cached and _fresh(cached) and not refresh:
            out.append(cached)
        else:
            to_fetch.append(key)

    if to_fetch:
        setup_proxy_env()
        try:
            import akshare  # noqa: F401
            has_ak = True
        except Exception:
            has_ak = False

        for n, key in enumerate(to_fetch, 1):
            name = ind = None
            src = "fallback"
            # 有兜底答案的先用兜底（快、稳定）；只有 --refresh 才强制走网络校准
            if has_ak and not _is_hk(key) and (refresh or key not in FALLBACK):
                name, ind = _fetch_em(key)
                time.sleep(0.2)
                if ind:
                    src = "eastmoney"
            if not ind and key in FALLBACK:
                name, ind = FALLBACK[key]
            if not ind:
                missing.append(key)
                ind = "未分类"
            l1 = L2_TO_L1.get(ind, "未分类" if ind == "未分类" else "其他")
            entry = {
                "code": key,
                "name": name or key,
                "industry": ind,
                "l1": l1,
                "source": src,
                "updatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            }
            _cache[key] = entry
            out.append(entry)
            dirty = True
            # 每 10 个落一次盘：整批跑几分钟，中途被打断也不该前功尽弃
            if dirty and n % 10 == 0:
                _save_cache()

    if dirty:
        _save_cache()
    return out, missing


def main():
    args = [a for a in sys.argv[1:] if a]
    refresh = False
    if args and args[0] == "--refresh":
        refresh = True
        args = args[1:]
    codes = (args[0] if args else "").replace("，", ",").split(",") if args else []
    codes = [c.strip() for c in codes if c.strip()]
    if not codes:
        print(json.dumps({"success": False, "error": "缺少代码参数"}, ensure_ascii=False))
        return
    data, missing = resolve(codes, refresh=refresh)
    print(json.dumps({"success": True, "data": data, "missing": missing}, ensure_ascii=False))


if __name__ == "__main__":
    main()
