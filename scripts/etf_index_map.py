#!/usr/bin/env python3
"""
etf_index_map.py — ETF 代码 → 标的指数映射

为什么需要：ETF 本身没有个股 PE，估值分位永远是缺失的。
用户买了科创50ETF（588080）时，"这个 ETF 贵不贵"只能看它跟的指数。
映射后 portfolio_advice 会用 index_valuations 里该指数的 5 年分位来当参考。

维护约定：同一指数的不同基金公司产品都要列（比如科创50 有 588000/588080/588090）。
新增 ETF 持仓时在这里补一行，否则该 ETF 会显示"估值数据缺失"。
"""

from __future__ import annotations

# ETF 代码 → (标的指数代码, 说明)
