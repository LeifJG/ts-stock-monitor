# ============================================================
# test_industry_l1.py — 行业一级分类映射（含「互联网平台」自定义分组）
# ------------------------------------------------------------
# 锁定三件事：
#   1. 平台型互联网公司单列成「互联网平台」，不再混进申万的「传媒」
#   2. 常见细分行业都能映射到申万一级，不允许悄悄落到「其他」
#   3. 取不到行业时是「未分类」，不能伪装成「其他」或其他真实行业
# ============================================================

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "scripts"))

from industry_data import map_l1, L2_TO_L1, PLATFORM_CODES, PLATFORM_L1, SCHEMA_VERSION


def test_平台公司单列():
    """腾讯/阿里/美团… 归互联网平台，而不是传媒"""
    for code in ("00700", "09988", "03690", "09999", "09618", "09888", "01024"):
        assert map_l1(code, "互联网科技") == PLATFORM_L1


def test_普通传媒公司仍然归传媒():
    # 分众传媒（广告）、芒果超媒（影视）是真传媒
    assert map_l1("002027", "传媒") == "传媒"
    assert map_l1("300413", "传媒") == "传媒"


def test_细分行业映射到申万一级():
    cases = {
        "半导体": "电子",
        "半导体设备": "电子",
        "消费电子": "电子",
        "银行": "银行",
        "白色家电": "家用电器",
        "医疗器械": "医药生物",
        "软件开发": "计算机",
        "光伏设备": "电力设备",
        "煤炭": "煤炭",
        "机器人": "机械设备",
        "文娱用品": "轻工制造",
        "互联网科技": "传媒",   # 非平台代码（如某些内容公司）仍归传媒
    }
    for l2, l1 in cases.items():
        got = map_l1("888001", l2)
        assert got == l1, f"{l2} 应映射为 {l1}，实际 {got}"


def test_取不到行业是未分类不是其他():
    assert map_l1("888002", None) == "未分类"
    assert map_l1("888002", "") == "未分类"
    assert map_l1("888002", "未分类") == "未分类"


def test_未知细分行业兜底为其他():
    assert map_l1("888003", "某个不存在的行业") == "其他"


def test_映射表没有明显漏项():
    """自选池里出现过的细分行业都要能落地到申万一级"""
    for l2 in ("白酒Ⅱ", "银行Ⅱ", "保险Ⅱ", "证券Ⅱ", "军工电子Ⅱ", "轨交设备Ⅱ", "航空装备Ⅱ",
               "IT服务Ⅱ", "元件", "小家电", "摩托车及其他", "自动化设备", "计算机设备"):
        assert l2 in L2_TO_L1, f"{l2} 未映射"


def test_口径版本号存在():
    """改映射必须 bump SCHEMA_VERSION，否则旧缓存不会失效"""
    assert isinstance(SCHEMA_VERSION, int) and SCHEMA_VERSION >= 2
